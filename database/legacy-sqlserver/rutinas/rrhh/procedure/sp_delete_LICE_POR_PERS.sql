CREATE PROCEDURE [dbo].[sp_delete_LICE_POR_PERS]
	@CODI_PERS_1 [char](5),
	@CODI_TIPO_LICE_2 [char](3),
	@FECH_INIC_3 [datetime]
WITH EXECUTE AS CALLER
AS
DELETE [LICENCIAS_POR_PERSONAL] 

WHERE 
	( [CODI_PERS]	 = @CODI_PERS_1 AND
	 [CODI_TIPO_LICE]	 = @CODI_TIPO_LICE_2 AND
	 [FECH_INIC]	 = @FECH_INIC_3)
GO
