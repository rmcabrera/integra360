CREATE PROCEDURE [dbo].[sp_delete_CONCEPTOS_AFECTOS_PLANILLAS]
	@CODI_CONC_1 [char](6),
	@CODI_TIPO_PLAN_2 [char](2),
	@FECH_REGI_3 [datetime]
WITH EXECUTE AS CALLER
AS
DELETE [CONCEPTOS_AFECTOS_PLANILLAS] 

WHERE 
	( [CODI_CONC]	 = @CODI_CONC_1 AND
	 [CODI_TIPO_PLAN]	 = @CODI_TIPO_PLAN_2 AND
	 [FECH_REGI]	 = @FECH_REGI_3)
GO
