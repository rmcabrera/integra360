CREATE PROCEDURE [dbo].[SP_Report_Planilla_Boni_Moto_Ingr]
	@mesa [char](8),
	@emb [char](5),
	@per [char](5),
	@tip [char](1)
WITH EXECUTE AS CALLER
AS
begin
	 SELECT PLANILLA_BONI_CONCEPTO.CODI_PLAN_BONI,  
	         PLANILLA_BONI_CONCEPTO.CODI_CONC,   
	         PLANILLA_BONI_CONCEPTO.AFECTO,   
	         PLANILLA_BONI_CONCEPTO.VALOR,   
	         PLANILLA_BONI_CONCEPTO.MONTO,   
	         PLANILLA_BONI_MOTO.CODI_PERS,   
	         PERSONAL.CODI_CARG,   
	         CARGOS.DESC_CARGO,   
	         CONCEPTOS.DESC_CONC  
	    FROM PLANILLA_BONI_MOTO,   
	         PLANILLA_BONI_CONCEPTO,   
	         CARGOS,   
	         PERSONAL,   
	         CONCEPTOS  
	   WHERE ( PLANILLA_BONI_CONCEPTO.CODI_PLAN_BONI = PLANILLA_BONI_MOTO.CODI_PLAN_BONI ) and  
	         ( PERSONAL.CODI_CARG = CARGOS.CODI_CARG ) and  
	         ( PERSONAL.CODI_PERS = PLANILLA_BONI_MOTO.CODI_PERS ) and  
	         ( CONCEPTOS.CODI_CONC = PLANILLA_BONI_CONCEPTO.CODI_CONC ) and  
	         ( ( PLANILLA_BONI_MOTO.MESANIO = @mesa ) AND  
	         ( PLANILLA_BONI_MOTO.CODI_UNID_OPER = @emb ) AND  
	         ( left(PLANILLA_BONI_CONCEPTO.CODI_CONC,1) = '1' ) AND  
	         (PLANILLA_BONI_CONCEPTO.CODI_CONC <> '199998' ) AND  
	         ( PLANILLA_BONI_CONCEPTO.CODI_CONC <> '199999' ) AND  
	         ( PLANILLA_BONI_MOTO.CODI_PERS = @per )  AND PLANILLA_BONI_MOTO.TIPO= @tip)    

end
GO
