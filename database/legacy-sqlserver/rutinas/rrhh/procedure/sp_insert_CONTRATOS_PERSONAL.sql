	 [CODI_UNID_OPER],
	 [CODI_CARG],
	 [TIPO_CONT],
	 [GRUP_OCUP],
	 [MODA_CONT]) 
 
VALUES 
	( @CODI_PERS_1,
	 @CODI_CONT_PERS_2,
	 @FECH_INIC_CONT_3,
	 @FECH_FIN_CONT_4,
	 @FECH_SALI_5,
	 @ESTA_CONT_6,
	 @SUEL_BASI_7,
	 @OBSERVACION_8,
	 @CODI_UNID_OPER_9,
	 @CODI_CARG_10,
	 @TIPO_CONT_11,
	 @GRUP_OCUP_12,
	 @MODA_CONT_13)
GO
