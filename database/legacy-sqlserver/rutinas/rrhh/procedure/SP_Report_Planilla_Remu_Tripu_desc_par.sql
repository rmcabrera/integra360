CREATE PROCEDURE [dbo].[SP_Report_Planilla_Remu_Tripu_desc_par]
	@sem [char](8),
	@emb [char](5),
	@per [char](5),
	@asi [char](1)
WITH EXECUTE AS CALLER
AS
begin
	 SELECT PLANILLA_TRIPULANTE_CONCEPTOS.CODI_PLAN_TRIP,   
	         PLANILLA_TRIPULANTE_CONCEPTOS.CODI_CONC,   
	         PLANILLA_TRIPULANTE_CONCEPTOS.AFECTO,   
	         PLANILLA_TRIPULANTE_CONCEPTOS.VALOR,   
	         PLANILLA_TRIPULANTE_CONCEPTOS.MONTO,   
	         PLANILLA_DE_TRIPULANTES.CODI_PERS,   
	         PERSONAL.CODI_CARG,   
	         CARGOS.DESC_CARGO,   
	         CONCEPTOS.DESC_CONC  
	    FROM PLANILLA_DE_TRIPULANTES,   
	         PLANILLA_TRIPULANTE_CONCEPTOS,   
	         CARGOS,   
	         PERSONAL,   
	         CONCEPTOS  
	   WHERE ( PLANILLA_TRIPULANTE_CONCEPTOS.CODI_PLAN_TRIP = PLANILLA_DE_TRIPULANTES.CODI_PLAN_TRIP ) and  
	         ( PERSONAL.CODI_CARG = CARGOS.CODI_CARG ) and  
	         ( PERSONAL.CODI_PERS = PLANILLA_DE_TRIPULANTES.CODI_PERS ) and  
	         ( CONCEPTOS.CODI_CONC = PLANILLA_TRIPULANTE_CONCEPTOS.CODI_CONC ) and  
	         ( ( PLANILLA_DE_TRIPULANTES.CODI_SEMA = @sem ) AND  
	         ( PLANILLA_DE_TRIPULANTES.CODI_UNID_OPER = @emb ) AND  
	         ( left(PLANILLA_TRIPULANTE_CONCEPTOS.CODI_CONC,1) = '2' ) AND  
	         ( PLANILLA_TRIPULANTE_CONCEPTOS.CODI_CONC <> '299999' ) AND  
	         ( PLANILLA_DE_TRIPULANTES.CODI_PERS = @per ) )     and nro_asis=@asi

end
GO
