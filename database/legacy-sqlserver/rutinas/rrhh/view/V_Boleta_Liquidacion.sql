CREATE VIEW [dbo].[V_Boleta_Liquidacion]
AS
SELECT     TOP 100 PERCENT dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, 
                      dbo.PERSONAL.CODI_CARG, dbo.PERSONAL.FECH_INGRE, dbo.PERSONAL.FECH_CESE, dbo.PERSONAL.MOTI_CESE, 
                      dbo.PLANILLA_DE_EMPLEADOS.MES, dbo.PLANILLA_DE_EMPLEADOS.ANIO, dbo.PERSONAL.CODI_PERS, 
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_PLAN_EMPL
FROM         dbo.PLANILLA_EMPLEADO_CONCEPTOS INNER JOIN
                      dbo.PLANILLA_DE_EMPLEADOS ON 
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_PLAN_EMPL = dbo.PLANILLA_DE_EMPLEADOS.CODI_PLAN_EMPL INNER JOIN
                      dbo.PERSONAL ON dbo.PLANILLA_DE_EMPLEADOS.CODI_PERS = dbo.PERSONAL.CODI_PERS
WHERE     (dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PLAN = '01') AND (dbo.PLANILLA_DE_EMPLEADOS.INDI_TIEM = 'M')
ORDER BY dbo.PLANILLA_DE_EMPLEADOS.ANIO, dbo.PLANILLA_DE_EMPLEADOS.MES, dbo.PERSONAL.APEL_1, 
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC
GO
