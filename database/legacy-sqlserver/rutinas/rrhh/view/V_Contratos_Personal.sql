CREATE VIEW [dbo].[V_Contratos_Personal]
AS
SELECT     dbo.CONTRATOS_PERSONAL.CODI_CONT_PERS, dbo.PERSONAL.APEL_1, dbo.CONTRATOS_PERSONAL.CODI_PERS, 
                      dbo.CONTRATOS_PERSONAL.CODI_CARG, dbo.CONTRATOS_PERSONAL.CODI_UNID_OPER, dbo.UNID_OPER.DESC_UNID_OPER, 
                      dbo.CARGOS.DESC_CARGO
FROM         dbo.CONTRATOS_PERSONAL INNER JOIN
                      dbo.PERSONAL ON dbo.CONTRATOS_PERSONAL.CODI_PERS = dbo.PERSONAL.CODI_PERS INNER JOIN
                      dbo.UNID_OPER ON dbo.CONTRATOS_PERSONAL.CODI_UNID_OPER = dbo.UNID_OPER.CODI_UNID_OPER INNER JOIN
                      dbo.CARGOS ON dbo.CONTRATOS_PERSONAL.CODI_CARG = dbo.CARGOS.CODI_CARG
GO
