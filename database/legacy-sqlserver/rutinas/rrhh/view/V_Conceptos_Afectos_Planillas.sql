CREATE VIEW [dbo].[V_Conceptos_Afectos_Planillas]
AS
SELECT     dbo.CONCEPTOS.DESC_CONC, dbo.CONCEPTOS_AFECTOS_PLANILLAS.CODI_CONC, dbo.CONCEPTOS_AFECTOS_PLANILLAS.CODI_TIPO_PLAN, 
                      dbo.TIPOS_PLANILLAS.DESC_TIPO_PLAN
FROM         dbo.CONCEPTOS INNER JOIN
                      dbo.CONCEPTOS_AFECTOS_PLANILLAS ON dbo.CONCEPTOS.CODI_CONC = dbo.CONCEPTOS_AFECTOS_PLANILLAS.CODI_CONC INNER JOIN
                      dbo.TIPOS_PLANILLAS ON dbo.CONCEPTOS_AFECTOS_PLANILLAS.CODI_TIPO_PLAN = dbo.TIPOS_PLANILLAS.CODI_TIPO_PLAN
GO
