CREATE VIEW [dbo].[V_REPO_VACA_PERS]
AS
SELECT     dbo.PERSONAL.CODI_PERS, dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, 
                      dbo.VACACIONES.FECH_INIC, dbo.VACACIONES.FECH_TERM, dbo.VACACIONES.ESTA_ACTI AS CON_SIN, dbo.VACACIONES.NRO_DIAS AS NUME, 
                      'V' AS TABLA, dbo.VACACIONES.OBSERVACIONES, 0 AS nro_hora_remu
FROM         dbo.PERSONAL INNER JOIN
                      dbo.VACACIONES ON dbo.PERSONAL.CODI_PERS = dbo.VACACIONES.CODI_PERS
GO
