CREATE VIEW [dbo].[V_Repo_Pago_Sist_Pens_fac]
AS
SELECT DISTINCT 
                      TOP 100 PERCENT dbo.PERSONAL.CODI_PERS, dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, 
                      dbo.PERSONAL.NOMB_2, dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PERS, dbo.PERSONAL.NRO_CUPSS, 
                      dbo.PLANILLA_DE_EMPLEADOS.CODI_PLAN_EMPL AS CODI_PLAN, dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PLAN, 
                      dbo.PLANILLA_DE_EMPLEADOS.ANIO, dbo.PLANILLA_DE_EMPLEADOS.MES, dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC, 
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS.VALOR, dbo.PLANILLA_EMPLEADO_CONCEPTOS.MONTO, dbo.PERSONAL.NRO_DOCU_IDEN, 
                      dbo.PLANILLA_DE_EMPLEADOS.FECH_INIC, dbo.PLANILLA_DE_EMPLEADOS.FECH_TERM, dbo.PLANILLA_DE_EMPLEADOS.CODI_SIST_PENS
FROM         dbo.PERSONAL INNER JOIN
                      dbo.PLANILLA_DE_EMPLEADOS ON dbo.PERSONAL.CODI_PERS = dbo.PLANILLA_DE_EMPLEADOS.CODI_PERS AND 
                      (  dbo.PLANILLA_DE_EMPLEADOS.INDI_TIEM = 'M' or dbo.PLANILLA_DE_EMPLEADOS.INDI_TIEM = 'S' ) INNER JOIN
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS ON 
                      dbo.PLANILLA_DE_EMPLEADOS.CODI_PLAN_EMPL = dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_PLAN_EMPL INNER JOIN
                      dbo.PERSONAL_POR_TIPO_TRABAJADOR ON dbo.PERSONAL.CODI_PERS = dbo.PERSONAL_POR_TIPO_TRABAJADOR.CODI_PERS
WHERE     (dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC = '199998' OR
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC >= '200031' AND dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC < '200040') AND 
                      (dbo.PLANILLA_DE_EMPLEADOS.ANIO >= '2002') AND (dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PLAN <> '07')
ORDER BY dbo.PERSONAL.CODI_PERS
GO
