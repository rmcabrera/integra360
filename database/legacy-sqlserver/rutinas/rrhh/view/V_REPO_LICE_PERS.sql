CREATE VIEW [dbo].[V_REPO_LICE_PERS]
AS
SELECT     dbo.PERSONAL.CODI_PERS, dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, 
                      dbo.LICENCIAS_POR_PERSONAL.FECH_INIC, dbo.LICENCIAS_POR_PERSONAL.FECH_TERM, 
                      dbo.LICENCIAS_POR_PERSONAL.GOCE_HABE AS CON_SIN, dbo.LICENCIAS_POR_PERSONAL.NRO_DIAS_REMU AS NUME, 
                      'TABLA ' = CASE WHEN dbo.LICENCIAS_POR_PERSONAL.codi_tipo_lice = '001' THEN 'D' WHEN dbo.LICENCIAS_POR_PERSONAL.codi_tipo_lice > '001'
                       THEN 'L' END, dbo.LICENCIAS_POR_PERSONAL.OBSERVACIONES, nro_hora_remu
FROM         dbo.PERSONAL INNER JOIN
                      dbo.LICENCIAS_POR_PERSONAL ON dbo.PERSONAL.CODI_PERS = dbo.LICENCIAS_POR_PERSONAL.CODI_PERS
GO
