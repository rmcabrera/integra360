CREATE VIEW [dbo].[VIEW_PERS_VACA]
AS
SELECT     dbo.VACACIONES.CODI_PERS, dbo.VACACIONES.FECH_INIC, dbo.VACACIONES.FECH_TERM, dbo.VACACIONES.NRO_DIAS, 
                      dbo.VACACIONES.ESTA_ACTI, dbo.VACACIONES.MES, dbo.VACACIONES.ANIO, dbo.PERSONAL_POR_TIPO_TRABAJADOR.CODI_TIPO_PERS
FROM         dbo.VACACIONES INNER JOIN
                      dbo.PERSONAL ON dbo.VACACIONES.CODI_PERS = dbo.PERSONAL.CODI_PERS INNER JOIN
                      dbo.PERSONAL_POR_TIPO_TRABAJADOR ON dbo.PERSONAL.CODI_PERS = dbo.PERSONAL_POR_TIPO_TRABAJADOR.CODI_PERS
WHERE     (dbo.VACACIONES.ESTA_ACTI = 1)
GO
