CREATE VIEW [dbo].[V_Planilla_Obreros_Conceptos]
AS
SELECT     dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, dbo.PERSONAL.FECH_CESE, 
                      dbo.PLANILLA_DE_OBREROS.ANIO, dbo.PLANILLA_DE_OBREROS.MES, dbo.PLANILLA_DE_OBREROS.CODI_TIPO_PLAN, 
                      dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC, dbo.PLANILLA_OBRERO_CONCEPTOS.VALOR, dbo.CONCEPTOS.DESC_CONC, 
                      dbo.PERSONAL.CODI_PERS, dbo.PLANILLA_DE_OBREROS.INDI_TIEM, dbo.PLANILLA_DE_OBREROS.FECH_INIC, 
                      dbo.PLANILLA_DE_OBREROS.FECH_TERM, dbo.PLANILLA_DE_OBREROS.CODI_SIST_PENS, dbo.PLANILLA_DE_OBREROS.CODI_TIPO_PERS, 
                      dbo.PLANILLA_DE_OBREROS.CODI_UNID_OPER, dbo.PLANILLA_DE_OBREROS.semana
FROM         dbo.PERSONAL INNER JOIN
                      dbo.PLANILLA_DE_OBREROS ON dbo.PERSONAL.CODI_PERS = dbo.PLANILLA_DE_OBREROS.CODI_PERS INNER JOIN
                      dbo.PLANILLA_OBRERO_CONCEPTOS ON 
                      dbo.PLANILLA_DE_OBREROS.CODI_PLAN_OBRE = dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_PLAN_OBRE INNER JOIN
                      dbo.CONCEPTOS ON dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC = dbo.CONCEPTOS.CODI_CONC
GO
