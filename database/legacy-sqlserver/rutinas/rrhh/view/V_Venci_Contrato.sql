CREATE VIEW [dbo].[V_Venci_Contrato]
AS
SELECT     dbo.CONTRATOS_PERSONAL.FECH_INIC_CONT, dbo.CONTRATOS_PERSONAL.FECH_FIN_CONT, dbo.CONTRATOS_PERSONAL.TIPO_CONT, 
                      dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, dbo.PERSONAL.FECH_INGRE, 
                      dbo.CARGOS.DESC_CARGO, dbo.UNID_OPER.DESC_UNID_OPER, dbo.Empresa.Razon_Social, dbo.PERSONAL.CODI_PERS, 
                      ISNULL(dbo.PERSONAL.FECH_CESE, CAST('01/01/2030' AS datetime)) AS fech_cese
FROM         dbo.CONTRATOS_PERSONAL INNER JOIN
                      dbo.PERSONAL ON dbo.CONTRATOS_PERSONAL.CODI_PERS = dbo.PERSONAL.CODI_PERS INNER JOIN
                      dbo.CARGOS ON dbo.CONTRATOS_PERSONAL.CODI_CARG = dbo.CARGOS.CODI_CARG INNER JOIN
                      dbo.UNID_OPER ON dbo.CONTRATOS_PERSONAL.CODI_UNID_OPER = dbo.UNID_OPER.CODI_UNID_OPER CROSS JOIN
                      dbo.Empresa

