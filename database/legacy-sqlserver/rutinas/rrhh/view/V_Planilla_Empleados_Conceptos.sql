CREATE VIEW [dbo].[V_Planilla_Empleados_Conceptos]
AS
SELECT     dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, dbo.PERSONAL.NOMB_2, dbo.PERSONAL.CODI_PERS, 
                      dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PLAN, dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC, dbo.CONCEPTOS.DESC_CONC, 
                      dbo.PLANILLA_DE_EMPLEADOS.ANIO, dbo.PLANILLA_DE_EMPLEADOS.MES, dbo.PLANILLA_EMPLEADO_CONCEPTOS.VALOR, 
                      dbo.PERSONAL.FECH_CESE, dbo.PLANILLA_DE_EMPLEADOS.INDI_TIEM, dbo.PLANILLA_DE_EMPLEADOS.FECH_INIC, 
                      dbo.PLANILLA_DE_EMPLEADOS.FECH_TERM, dbo.PLANILLA_DE_EMPLEADOS.CODI_SIST_PENS, dbo.PLANILLA_DE_EMPLEADOS.CODI_TIPO_PERS, 
                      dbo.PLANILLA_DE_EMPLEADOS.semana, dbo.PLANILLA_DE_EMPLEADOS.CODI_UNID_OPER
FROM         dbo.PERSONAL INNER JOIN
                      dbo.PLANILLA_DE_EMPLEADOS ON dbo.PERSONAL.CODI_PERS = dbo.PLANILLA_DE_EMPLEADOS.CODI_PERS INNER JOIN
                      dbo.PLANILLA_EMPLEADO_CONCEPTOS ON 
                      dbo.PLANILLA_DE_EMPLEADOS.CODI_PLAN_EMPL = dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_PLAN_EMPL INNER JOIN
                      dbo.CONCEPTOS ON dbo.PLANILLA_EMPLEADO_CONCEPTOS.CODI_CONC = dbo.CONCEPTOS.CODI_CONC
GO
