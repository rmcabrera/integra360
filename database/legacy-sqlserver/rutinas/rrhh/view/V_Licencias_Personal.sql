CREATE VIEW [dbo].[V_Licencias_Personal]
AS
SELECT     dbo.LICENCIAS_POR_PERSONAL.CODI_PERS, dbo.TIPOS_LICENCIAS.DESC_LICE, dbo.LICENCIAS_POR_PERSONAL.CODI_TIPO_LICE, 
                      dbo.PERSONAL.APEL_1,  dbo.PERSONAL.APEL_2,  dbo.PERSONAL.nomb_1,  dbo.PERSONAL.nomb_2
FROM         dbo.LICENCIAS_POR_PERSONAL INNER JOIN
                      dbo.PERSONAL ON dbo.LICENCIAS_POR_PERSONAL.CODI_PERS = dbo.PERSONAL.CODI_PERS INNER JOIN
                      dbo.TIPOS_LICENCIAS ON dbo.LICENCIAS_POR_PERSONAL.CODI_TIPO_LICE = dbo.TIPOS_LICENCIAS.CODI_TIPO_LICE
GO
