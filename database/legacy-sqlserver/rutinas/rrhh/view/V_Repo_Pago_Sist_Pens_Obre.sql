CREATE VIEW [dbo].[V_Repo_Pago_Sist_Pens_Obre]
AS
SELECT DISTINCT 
                      TOP 100 PERCENT dbo.PERSONAL.CODI_PERS, dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, 
                      dbo.PERSONAL.NOMB_2, dbo.PLANILLA_DE_OBREROS.CODI_TIPO_PERS, dbo.PERSONAL.NRO_CUPSS, 
                      dbo.PLANILLA_DE_OBREROS.CODI_PLAN_OBRE AS CODI_PLAN, dbo.PLANILLA_DE_OBREROS.CODI_TIPO_PLAN, 
                      dbo.PLANILLA_DE_OBREROS.ANIO, dbo.PLANILLA_DE_OBREROS.MES, dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC, 
                      dbo.PLANILLA_OBRERO_CONCEPTOS.VALOR, dbo.PLANILLA_OBRERO_CONCEPTOS.MONTO, dbo.PERSONAL.NRO_DOCU_IDEN, 
                      dbo.PLANILLA_DE_OBREROS.FECH_INIC, dbo.PLANILLA_DE_OBREROS.FECH_TERM, dbo.PLANILLA_DE_OBREROS.CODI_SIST_PENS
FROM         dbo.PERSONAL INNER JOIN
                      dbo.PLANILLA_DE_OBREROS ON dbo.PERSONAL.CODI_PERS = dbo.PLANILLA_DE_OBREROS.CODI_PERS AND 
                      dbo.PLANILLA_DE_OBREROS.INDI_TIEM = 'M' INNER JOIN
                      dbo.PLANILLA_OBRERO_CONCEPTOS ON 
                      dbo.PLANILLA_DE_OBREROS.CODI_PLAN_OBRE = dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_PLAN_OBRE INNER JOIN
                      dbo.PERSONAL_POR_TIPO_TRABAJADOR ON dbo.PERSONAL.CODI_PERS = dbo.PERSONAL_POR_TIPO_TRABAJADOR.CODI_PERS
WHERE     (dbo.PLANILLA_DE_OBREROS.ANIO >= '2002') AND (dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC = '199998' OR
                      dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC >= '200031' AND dbo.PLANILLA_OBRERO_CONCEPTOS.CODI_CONC < '200040') AND 
                      (dbo.PLANILLA_DE_OBREROS.CODI_TIPO_PLAN <> '07')
ORDER BY dbo.PERSONAL.CODI_PERS
GO
