CREATE PROCEDURE [dbo].[Sp_update_DETA_ZARP]
	@CODI_ZARP [char](10),
	@CODI_ESPE [char](2),
	@CANTIDAD [decimal](9, 2),
	@CODI_UNID_MEDI_CANT [char](2),
	@TAMA_MINI_ESPE [decimal](9, 2),
	@TAMA_MAXI_ESPE [decimal](9, 2),
	@CODI_UNID_MEDI_TAMA [char](2)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_ZARPE] 

SET  [CODI_ZARP]	 = @CODI_ZARP,
	 [CODI_ESPE]	 = @CODI_ESPE,
	 [CANTIDAD]	 = @CANTIDAD,
	 [CODI_UNID_MEDI_CANT]	 = @CODI_UNID_MEDI_CANT,
	 [TAMA_MINI_ESPE]	 = @TAMA_MINI_ESPE,
	 [TAMA_MAXI_ESPE]	 = @TAMA_MAXI_ESPE,
	 [CODI_UNID_MEDI_TAMA]	 = @CODI_UNID_MEDI_TAMA 

WHERE 
	( [CODI_ZARP]	 = @CODI_ZARP AND
	 [CODI_ESPE]	 = @CODI_ESPE)
GO
