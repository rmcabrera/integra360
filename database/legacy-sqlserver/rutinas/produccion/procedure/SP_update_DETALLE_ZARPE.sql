CREATE PROCEDURE [dbo].[SP_update_DETALLE_ZARPE]
	@CODI_DETA_ZARP_1 [char](15),
	@CODI_ESPE_1 [char](2),
	@CANTIDAD_1 [decimal](18, 3),
	@CODI_UNID_MEDI_CANT_1 [char](2),
	@TAMA_MINI_ESPE_1 [decimal](18, 2),
	@TAMA_MAXI_ESPE_1 [decimal](18, 2),
	@CODI_UNID_MEDI_TAMA_1 [char](2),
	@CODI_CLIE_PROV_1 [char](5),
	@SERI_GUIA_1 [char](5),
	@NRO_GUIA_1 [char](10)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_ZARPE] 

SET  	 [CODI_ESPE]	 = @CODI_ESPE_1,
	 [CANTIDAD]	 = @CANTIDAD_1,
	 [CODI_UNID_MEDI_CANT]	 = @CODI_UNID_MEDI_CANT_1,
	 [TAMA_MINI_ESPE]	 = @TAMA_MINI_ESPE_1,
	 [TAMA_MAXI_ESPE]	 = @TAMA_MAXI_ESPE_1,
	 [CODI_UNID_MEDI_TAMA]	 = @CODI_UNID_MEDI_TAMA_1,
	 [CODI_CLIE_PROV]	 = @CODI_CLIE_PROV_1,
	 [SERI_GUIA]	 = @SERI_GUIA_1,
	 [NRO_GUIA]	 = @NRO_GUIA_1 

WHERE 
	( [CODI_DETA_ZARP]	 = @CODI_DETA_ZARP_1)
GO
