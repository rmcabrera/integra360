CREATE PROCEDURE [dbo].[sp_update_PREC_PACT]
	@CODI_SEMA [char](6),
	@CODI_CLIE_PROV [char](5),
	@CODI_ESPE [char](2),
	@PREC_PACT [decimal](9, 2),
	@CODI_MONE [char](2)
WITH EXECUTE AS CALLER
AS
UPDATE [PRECIO_PACTADO] 

SET  [CODI_SEMA]	 = @CODI_SEMA,
	 [CODI_CLIE_PROV]	 = @CODI_CLIE_PROV,
	 [CODI_ESPE]	 = @CODI_ESPE,
	 [PREC_PACT]	 = @PREC_PACT,
	 [CODI_MONE]	 = @CODI_MONE 

WHERE 
	( [CODI_SEMA]	 = @CODI_SEMA AND
	 [CODI_CLIE_PROV]	 = @CODI_CLIE_PROV  AND
	 [CODI_ESPE]	 = @CODI_ESPE)
GO
