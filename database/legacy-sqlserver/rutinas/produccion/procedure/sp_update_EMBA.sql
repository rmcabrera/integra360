CREATE PROCEDURE [dbo].[sp_update_EMBA]
	@CODI_UNID_OPER_1 [char](1),
	@CODI_UNID_OPER_2 [char](5),
	@DESC_UNID_OPER_3 [varchar](100),
	@CAPA_BODE_4 [numeric](9, 2),
	@NRO_MATRI_5 [varchar](15),
	@LUGA_CONS_6 [varchar](50)
WITH EXECUTE AS CALLER
AS
UPDATE [EMBARCACIONES] 

SET  [CODI_UNID_OPER]	 = @CODI_UNID_OPER_2,
	 [DESC_UNID_OPER]	 = @DESC_UNID_OPER_3,
	 [CAPA_BODE]	 = @CAPA_BODE_4,
	 [NRO_MATRI]	 = @NRO_MATRI_5,
	 [LUGA_CONS]	 = @LUGA_CONS_6 

WHERE 
	( [CODI_UNID_OPER]	 = @CODI_UNID_OPER_1)
GO
