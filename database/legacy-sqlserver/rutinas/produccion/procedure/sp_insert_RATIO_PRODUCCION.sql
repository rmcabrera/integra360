CREATE PROCEDURE [dbo].[sp_insert_RATIO_PRODUCCION]
	@CODI_RATI_PROD_1 [char](10),
	@CODI_TURN_1 [char](2),
	@CODI_RATI_1 [char](2),
	@FECH_RATI_PROD_1 [datetime],
	@VALO_RATI_PROD_1 [numeric](12, 3),
	@CODI_UNID_NEGO_1 [char](2)
WITH EXECUTE AS CALLER
AS
INSERT INTO [RATIO_PRODUCCION] 
	 ( [CODI_RATI_PROD],
	 [CODI_TURN],
	 [CODI_RATI],
	 [FECH_RATI_PROD],
	 [VALO_RATI_PROD],
	 [CODI_UNID_NEGO]) 
 
VALUES 
	( @CODI_RATI_PROD_1,
	 @CODI_TURN_1,
	 @CODI_RATI_1,
	 @FECH_RATI_PROD_1,
	 @VALO_RATI_PROD_1,
	 @CODI_UNID_NEGO_1)
GO
