CREATE VIEW [dbo].[V_Faena_Pesca]
AS
SELECT     dbo.ZARPES.CODI_ZARP, dbo.ZARPES.FECH_REPO, dbo.SEMANA.CODI_SEMA, dbo.SEMANA.NRO_SEMA, dbo.SEMANA.FECH_INIC, 
                      dbo.SEMANA.FECH_TERM, dbo.ZARPES.FECH_DESC, dbo.ZARPES.CODI_UNID_OPER, dbo.EMBARCACIONES.DESC_UNID_OPER, 
                      dbo.Puerto.Desc_Puer, dbo.ZARPES.ZONA_PESC, dbo.ZARPES.FECH_ZARP, dbo.ZARPES.PESC_REAL, dbo.ZARPES.OBSE_PESC, 
                      dbo.ZARPES.CODI_PUER2, dbo.ZARPES.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, dbo.ZARPES.FECH_ARRI
FROM         dbo.ZARPES INNER JOIN
                      dbo.SEMANA ON dbo.ZARPES.CODI_SEMA = dbo.SEMANA.CODI_SEMA INNER JOIN
                      dbo.EMBARCACIONES ON dbo.ZARPES.CODI_UNID_OPER = dbo.EMBARCACIONES.CODI_UNID_OPER LEFT OUTER JOIN
                      dbo.Puerto ON dbo.ZARPES.CODI_PUER2 = dbo.Puerto.Codi_Puer LEFT OUTER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.ZARPES.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV
GO
