CREATE VIEW [dbo].[V_FacturaPesca]
AS
SELECT     dbo.FACTURA_PESCA.CODI_FACT_PESC, dbo.FACTURA_PESCA.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, 
                      dbo.FACTURA_PESCA.FECH_EMIS, dbo.FACTURA_PESCA.VALO_VENT, dbo.FACTURA_PESCA.IGV, dbo.FACTURA_PESCA.VALO_TOTA, 
                      dbo.FACTURA_PESCA.CODI_MONE, dbo.MONEDAS.DESC_MONE, dbo.FACTURA_PESCA.SER_FACT, dbo.FACTURA_PESCA.NRO_FACT, 
                      dbo.FACTURA_PESCA.TIPO_FACT, dbo.FACTURA_PESCA.CODI_UNID_OPER, dbo.UNID_OPER.DESC_UNID_OPER, dbo.FACTURA_PESCA.CODI_SEMA, 
                      dbo.SEMANA.NRO_SEMA, dbo.FACTURA_PESCA.PORC_DETR, dbo.FACTURA_PESCA.Estado
FROM         dbo.CLIENTE_PROVEEDOR INNER JOIN
                      dbo.FACTURA_PESCA ON dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV = dbo.FACTURA_PESCA.CODI_CLIE_PROV INNER JOIN
                      dbo.MONEDAS ON dbo.FACTURA_PESCA.CODI_MONE = dbo.MONEDAS.CODI_MONE INNER JOIN
                      dbo.UNID_OPER ON dbo.FACTURA_PESCA.CODI_UNID_OPER = dbo.UNID_OPER.CODI_UNID_OPER INNER JOIN
                      dbo.SEMANA ON dbo.FACTURA_PESCA.CODI_SEMA = dbo.SEMANA.CODI_SEMA
GO
