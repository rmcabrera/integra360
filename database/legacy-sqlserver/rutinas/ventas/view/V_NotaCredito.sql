CREATE VIEW [dbo].[V_NotaCredito]
AS
SELECT     dbo.NOTA_CREDITO.CODI_NOTA_CRED, dbo.NOTA_CREDITO.SER_NOTA_CRED, dbo.NOTA_CREDITO.NRO_NOTA_CRED, 
                      dbo.NOTA_CREDITO.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, dbo.NOTA_CREDITO.FECH_NOTA_CRED, 
                      dbo.NOTA_CREDITO.VALO_VENT, dbo.NOTA_CREDITO.IGV, dbo.NOTA_CREDITO.PREC_VENT, dbo.MONEDAS.CODI_MONE, 
                      dbo.MONEDAS.DESC_MONE, dbo.NOTA_CREDITO.OBSERVACION, dbo.UNID_OPER.DESC_UNID_OPER, dbo.SEMANA.NRO_SEMA, 
                      dbo.SEMANA.ANIOMES, dbo.NOTA_CREDITO.CODI_UNID_OPER, dbo.NOTA_CREDITO.CODI_SEMA, dbo.NOTA_CREDITO.CODI_DETA_ZARP, 
                      dbo.NOTA_CREDITO.Estado
FROM         dbo.NOTA_CREDITO INNER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.NOTA_CREDITO.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV INNER JOIN
                      dbo.MONEDAS ON dbo.NOTA_CREDITO.CODI_MONE = dbo.MONEDAS.CODI_MONE LEFT OUTER JOIN
                      dbo.UNID_OPER ON dbo.NOTA_CREDITO.CODI_UNID_OPER = dbo.UNID_OPER.CODI_UNID_OPER LEFT OUTER JOIN
                      dbo.SEMANA ON dbo.NOTA_CREDITO.CODI_SEMA = dbo.SEMANA.CODI_SEMA
GO
