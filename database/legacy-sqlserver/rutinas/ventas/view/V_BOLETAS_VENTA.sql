CREATE VIEW [dbo].[V_BOLETAS_VENTA]
AS
SELECT     dbo.BOLETAS.CODI_BOLE, dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, dbo.BOLETAS.FECHA, 
                      dbo.BOLETAS.SERIE, dbo.BOLETAS.NUMERO, dbo.MONEDAS.DESC_MONE, dbo.BOLETAS.MONTO, dbo.BOLETAS.ESTADO, dbo.BOLETAS.TIPO
FROM         dbo.BOLETAS INNER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.BOLETAS.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV INNER JOIN
                      dbo.MONEDAS ON dbo.BOLETAS.CODI_MONE = dbo.MONEDAS.CODI_MONE
GO
