CREATE VIEW [dbo].[V_NotaDebito]
AS
SELECT     dbo.NOTA_DEBITO.CODI_NOTA_DEBI, dbo.NOTA_DEBITO.SER_NOTA_DEBI, dbo.NOTA_DEBITO.NRO_NOTA_DEBI, 
                      dbo.NOTA_DEBITO.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, dbo.NOTA_DEBITO.FECH_NOTA_DEBI, 
                      dbo.NOTA_DEBITO.VALO_VENT, dbo.NOTA_DEBITO.IGV, dbo.NOTA_DEBITO.PREC_VENT, dbo.NOTA_DEBITO.CODI_MONE, 
                      dbo.MONEDAS.DESC_MONE, dbo.NOTA_DEBITO.OBSERVACION1, dbo.NOTA_DEBITO.OBSERVACION2, dbo.NOTA_DEBITO.codi_unid_oper, 
                      dbo.UNID_OPER.DESC_UNID_OPER, dbo.NOTA_DEBITO.codi_sema, dbo.SEMANA.NRO_SEMA, dbo.NOTA_DEBITO.CODI_DETA_ZARP, 
                      dbo.NOTA_DEBITO.Estado
FROM         dbo.NOTA_DEBITO INNER JOIN
                      dbo.MONEDAS ON dbo.NOTA_DEBITO.CODI_MONE = dbo.MONEDAS.CODI_MONE INNER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.NOTA_DEBITO.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV LEFT OUTER JOIN
                      dbo.SEMANA ON dbo.NOTA_DEBITO.codi_sema = dbo.SEMANA.CODI_SEMA LEFT OUTER JOIN
                      dbo.UNID_OPER ON dbo.NOTA_DEBITO.codi_unid_oper = dbo.UNID_OPER.CODI_UNID_OPER
GO
