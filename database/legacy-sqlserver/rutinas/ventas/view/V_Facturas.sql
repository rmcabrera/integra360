CREATE VIEW [dbo].[V_Facturas]
AS
SELECT     dbo.FACTURA.CODI_FACT, dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, dbo.FACTURA.FECH_FACT, 
                      dbo.FACTURA.SER_FACT, dbo.FACTURA.NRO_FACT, dbo.MONEDAS.DESC_MONE, dbo.FACTURA.VALO_FACT, dbo.FACTURA.IGV_FACT, 
                      dbo.FACTURA.TOTA_FACT, dbo.FACTURA.CODI_ORDE_GRUA, dbo.FACTURA.ESTADO, dbo.FACTURA.TIPO_FACT
FROM         dbo.FACTURA INNER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.FACTURA.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV INNER JOIN
                      dbo.MONEDAS ON dbo.FACTURA.CODI_MONE = dbo.MONEDAS.CODI_MONE
GO
