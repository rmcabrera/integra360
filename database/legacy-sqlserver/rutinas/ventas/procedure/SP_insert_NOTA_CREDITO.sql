	( @CODI_NOTA_CRED_1,
	 @SER_NOTA_CRED_1,
	 @NRO_NOTA_CRED_1,
	 @CODI_CLIE_PROV_1,
	 @FECH_NOTA_CRED_1,
	 @VALO_VENT_1,
	 @IGV_1,
	 @PREC_VENT_1,
	 @CODI_MONE_1,
	 @OBSERVACION_1,
	 @CODI_UNID_OPER_1 ,
	 @CODI_SEMA_1 ,
	@CODI_DETA_ZARP_1)
GO
