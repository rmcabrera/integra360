CREATE PROCEDURE [dbo].[SP_insert_INGRESO_PROD_TERMINADOS]
	@CODI_INGR_PRO_TERM_1 [char](10),
	@CODI_TURN_1 [char](2),
	@CODI_SUB_FAMI_PROD_1 [char](4),
	@MOTI_INGR_1 [varchar](100),
	@OBSE_INGR_1 [varchar](100),
	@UNID_MEDI_1 [char](2),
	@CODI_ALMA_1 [char](3),
	@FECH_INGR_1 [datetime]
WITH EXECUTE AS CALLER
AS
INSERT INTO [INGRESO_PROD_TERMINADOS] 
	 ( [CODI_INGR_PRO_TERM],
	 [CODI_TURN],
	 [CODI_SUB_FAMI_PROD],
	 [MOTI_INGR],
	 [OBSE_INGR],
	 [UNID_MEDI],
	 [CODI_ALMA],
	 [FECH_INGR]) 
 
VALUES 
	( @CODI_INGR_PRO_TERM_1,
	 @CODI_TURN_1,
	 @CODI_SUB_FAMI_PROD_1,
	 @MOTI_INGR_1,
	 @OBSE_INGR_1,
	 @UNID_MEDI_1,
	 @CODI_ALMA_1,
	 @FECH_INGR_1)
GO
