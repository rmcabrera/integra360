CREATE PROCEDURE [dbo].[SP_insert_DETALLE_CONSUMO_PROD]
	@CODI_CONS_PROD_1 [char](20),
	@CODI_PROD_DIA_1 [char](10),
	@CODI_PROD_1 [char](8),
	@TIPO_CONS_PROD_1 [char](1),
	@CANT_CONS_PROD_1 [numeric](12, 4),
	@CODI_ESPE_1 [char](2),
	@DESC_ESPE_1 [varchar](100),
	@CODI_VALE_1 [char](10)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_CONSUMO_PROD] 
	 ( [CODI_CONS_PROD],
	 [CODI_PROD_DIA],
	 [CODI_PROD],
	 [TIPO_CONS_PROD],
	 [CANT_CONS_PROD],
	 [CODI_ESPE],
	 [DESC_ESPE],
	 [CODI_VALE]) 
 
VALUES 
	( @CODI_CONS_PROD_1,
	 @CODI_PROD_DIA_1,
	 @CODI_PROD_1,
	 @TIPO_CONS_PROD_1,
	 @CANT_CONS_PROD_1,
	 @CODI_ESPE_1,
	 @DESC_ESPE_1,
	 @CODI_VALE_1)
GO
