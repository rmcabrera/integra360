CREATE PROCEDURE [dbo].[SP_insert_PRODUCCION_DIA]
	@CODI_PROD_DIA_1 [char](10),
	@FECH_PROD_DIA_1 [datetime],
	@CODI_PROD_1 [char](8),
	@CODI_TURN_1 [char](2),
	@CODI_UNID_NEGO_1 [char](2)
WITH EXECUTE AS CALLER
AS
INSERT INTO [PRODUCCION_DIA] 
	 ( [CODI_PROD_DIA],
	 [FECH_PROD_DIA],
	 [CODI_PROD],
	 [CODI_TURN],
	 [CODI_UNID_NEGO]) 
 
VALUES 
	( @CODI_PROD_DIA_1,
	 @FECH_PROD_DIA_1,
	 @CODI_PROD_1,
	 @CODI_TURN_1,
	 @CODI_UNID_NEGO_1)
GO
