CREATE PROCEDURE [dbo].[sp_update_COTI_UNIC]
	@CODI_COTI_UNIC_PROV [char](10),
	@CODI_COTI_PROV [char](10),
	@ESTADO [char](1),
	@FECH_COTI_UNIC [datetime]
WITH EXECUTE AS CALLER
AS
UPDATE [COTIZACION_UNICA] 

SET 
	 [ESTADO]	 = @ESTADO,
	 [FECH_COTI_UNIC]	 = @FECH_COTI_UNIC 

WHERE 
	( [CODI_COTI_UNIC_PROV]	 = @CODI_COTI_UNIC_PROV AND
	 [CODI_COTI_PROV]	 = @CODI_COTI_PROV)
GO
