CREATE PROCEDURE [dbo].[sp_update_UNIDAD_MEDIDA]
	@CODI_UNID_MEDI_1 [char](1),
	@CODI_UNID_MEDI_2 [char](2),
	@DESC_UNID_MEDI [varchar](100),
	@TIPO_UNID_MEDI [varchar](50),
	@SIMB_UNID_MEDI [char](2)
WITH EXECUTE AS CALLER
AS
UPDATE [UNIDAD_MEDIDA] 

SET  [CODI_UNID_MEDI]	 = @CODI_UNID_MEDI_2,
	 [DESC_UNID_MEDI]	 = @DESC_UNID_MEDI,
	 [TIPO_UNID_MEDI]	 = @TIPO_UNID_MEDI,
	 [SIMB_UNID_MEDI]	 = @SIMB_UNID_MEDI 

WHERE 
	( [CODI_UNID_MEDI]	 = @CODI_UNID_MEDI_1)
GO
