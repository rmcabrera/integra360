CREATE PROCEDURE [dbo].[sp_insert_COTI_UNIC]
	@CODI_COTI_UNIC_PROV [char](10),
	@CODI_COTI_PROV [char](10),
	@ESTADO [char](1),
	@FECH_COTI_UNIC [datetime]
WITH EXECUTE AS CALLER
AS
INSERT INTO [COTIZACION_UNICA] 
	 ( [CODI_COTI_UNIC_PROV],
	 [CODI_COTI_PROV],
	 [ESTADO],
	 [FECH_COTI_UNIC]) 
 
VALUES 
	( @CODI_COTI_UNIC_PROV,
	 @CODI_COTI_PROV,
	 @ESTADO,
	 @FECH_COTI_UNIC)
GO
