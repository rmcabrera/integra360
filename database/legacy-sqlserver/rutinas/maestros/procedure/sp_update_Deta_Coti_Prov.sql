CREATE PROCEDURE [dbo].[sp_update_Deta_Coti_Prov]
	@CODI_DETA_COTI_PROV [char](12),
	@CANTIDAD [decimal](9, 2),
	@CODI_UNID_MEDI_TIEM [char](2),
	@TIEMP_RESP [decimal](9, 2),
	@CODI_MONE [char](2),
	@PREC_UNIT [decimal](9, 2),
	@ESTADO [char](1)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_COTIZACION_POR_PROVEEDOR] 

SET 	 [CANTIDAD]	 		= @CANTIDAD,
	 [CODI_UNID_MEDI_TIEM]	= @CODI_UNID_MEDI_TIEM,
	 [TIEMP_RESP]			= @TIEMP_RESP,
	 [CODI_MONE]			= @CODI_MONE,
	 [PREC_UNIT]			= @PREC_UNIT,
	 [ESTADO]	 		= @ESTADO 

WHERE 
	( [CODI_DETA_COTI_PROV]	 = @CODI_DETA_COTI_PROV)
GO
