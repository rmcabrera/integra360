CREATE PROCEDURE [dbo].[sp_update_Coti_Por_Prov]
	@CODI_COTI_PROV [char](10),
	@FECH_COTI_PROV [datetime],
	@CODI_UNID_MEDI [char](2),
	@TIEMP_PLAZ_CRED [decimal](9, 2),
	@ESTADO [char](1),
	@CODI_MONE [char](2),
	@PREC_TOTA [decimal](9, 2)
WITH EXECUTE AS CALLER
AS
UPDATE [COTIZACION_POR_PROVEEDOR] 

SET  	[FECH_COTI_PROV]	 = @FECH_COTI_PROV,
	[CODI_UNID_MEDI]	 = @CODI_UNID_MEDI,
	[TIEMP_PLAZ_CRED]	 = @TIEMP_PLAZ_CRED,
	[ESTADO]	 	 = @ESTADO, 
	[CODI_MONE]		 = @CODI_MONE,
	[PREC_TOTA]		 = @PREC_TOTA

WHERE 
	( [CODI_COTI_PROV]	 = @CODI_COTI_PROV)
GO
