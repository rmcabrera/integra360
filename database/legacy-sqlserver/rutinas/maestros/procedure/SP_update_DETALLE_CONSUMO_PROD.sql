CREATE PROCEDURE [dbo].[SP_update_DETALLE_CONSUMO_PROD]
	@CODI_CONS_PROD_1 [char](20),
	@CODI_PROD_DIA_1 [char](10),
	@CANT_CONS_PROD_1 [numeric](12, 4)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_CONSUMO_PROD] 

SET  	 [CODI_PROD_DIA]	 = @CODI_PROD_DIA_1,
	 [CANT_CONS_PROD]	 = @CANT_CONS_PROD_1

WHERE 
	( [CODI_CONS_PROD]	 = @CODI_CONS_PROD_1)
GO
