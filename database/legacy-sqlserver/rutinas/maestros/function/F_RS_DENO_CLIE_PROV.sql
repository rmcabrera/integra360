CREATE FUNCTION [dbo].[F_RS_DENO_CLIE_PROV](@CODI_CLIE_PROV [char](5), @TIPO_MOST [char](4))
RETURNS [varchar](200) WITH EXECUTE AS CALLER
AS 
BEGIN 
	DECLARE @RT VARCHAR(200)
	DECLARE @V VARCHAR(200)
	DECLARE @TP VARCHAR(200)
	IF @TIPO_MOST = 'RS' 
	BEGIN
		SET @TP = (SELECT TIPO_PERS FROM CLIENTE_PROVEEDOR WHERE CODI_CLIE_PROV = @CODI_CLIE_PROV)
		IF UPPER(@TP )=  'NATURAL' 
		BEGIN
			SET @RT = (SELECT ISNULL(APEL_1,'') + ' ' + ISNULL(APEL_2 , '') + ' ' + ISNULL(NOMB_1 , '') + ' ' +  ISNULL(NOMB_2 , '')  
					FROM CLIENTE_PROVEEDOR WHERE CODI_CLIE_PROV = @CODI_CLIE_PROV) 			
		END
		ELSE
		BEGIN
			SET @RT = (SELECT ISNULL(RAZO_SOCI ,'') FROM CLIENTE_PROVEEDOR WHERE CODI_CLIE_PROV = @CODI_CLIE_PROV) 
		END
	END
	ELSE
	BEGIN
		IF @TIPO_MOST = 'RUC' 
		BEGIN
			SET @RT = (SELECT ISNULL(RUC ,'') FROM CLIENTE_PROVEEDOR WHERE CODI_CLIE_PROV = @CODI_CLIE_PROV) 
		END
		ELSE
		BEGIN
			SET @RT = (SELECT ISNULL(DENOMINACION ,'') FROM CLIENTE_PROVEEDOR WHERE CODI_CLIE_PROV = @CODI_CLIE_PROV) 
		END
	END	

	RETURN @RT
END
GO
