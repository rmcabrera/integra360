CREATE VIEW [dbo].[V_REPO_VACA_LICE_PERS]
AS
SELECT     TOP 100 PERCENT CODI_PERS, APEL_1, APEL_2, NOMB_1, NOMB_2, FECH_INIC, FECH_TERM, CON_SIN, NUME, TABLA, 
		OBSERVACIONES, nro_hora_remu
FROM         (SELECT     CODI_PERS, APEL_1, APEL_2, NOMB_1, NOMB_2, FECH_INIC, FECH_TERM, CON_SIN, NUME, TABLA, 
		OBSERVACIONES, nro_hora_remu
                       FROM          dbo.V_REPO_LICE_PERS
                       UNION
                       SELECT     CODI_PERS, APEL_1, APEL_2, NOMB_1, NOMB_2, FECH_INIC, FECH_TERM, CON_SIN, NUME, TABLA, OBSERVACIONES, 0
                       FROM         dbo.V_REPO_VACA_PERS) REPO_LICE_VACA_PERS
GO
