CREATE VIEW [dbo].[V_Deposito_CTS]
AS
SELECT     dbo.PERSONAL.NRO_DOCU_IDEN, dbo.PERSONAL.APEL_1, dbo.PERSONAL.APEL_2, dbo.PERSONAL.NOMB_1, 
                      dbo.CTA_CTE_PERSONAL.NRO_CTA_CTE, dbo.DATOS_CTS.IMPO_DOLA, dbo.CTA_CTE_PERSONAL.CODI_BANC, dbo.PERSONAL.NOMB_2, 
                      dbo.DATOS_CTS.ANIO, dbo.DATOS_CTS.MES, dbo.CTA_CTE_PERSONAL.CODI_PERS, dbo.DATOS_CTS.FECH_PAGO, dbo.DATOS_CTS.FECH_VENC, 
                      dbo.DATOS_CTS.MONT_INTE_DIAR, dbo.DATOS_CTS.TIPO_CAMB, dbo.DATOS_CTS.TIPO_CTS
FROM         dbo.DATOS_CTS INNER JOIN
                      dbo.PERSONAL ON dbo.DATOS_CTS.CODI_PERS = dbo.PERSONAL.CODI_PERS INNER JOIN
                      dbo.CTA_CTE_PERSONAL ON dbo.PERSONAL.CODI_PERS = dbo.CTA_CTE_PERSONAL.CODI_PERS
WHERE     (dbo.CTA_CTE_PERSONAL.TIPO_CTA_CTE = '01')
GO
