CREATE VIEW [dbo].[V_Nota_Ingreso]
AS
SELECT     dbo.NOTA_INGRESO.CODI_NOTA_INGR, dbo.NOTA_INGRESO.NRO_SERI, dbo.NOTA_INGRESO.NRO_DOCU, dbo.NOTA_INGRESO.FECH_NOTA_INGR, 
                      dbo.NOTA_INGRESO.TIPO_NOTA_INGR, dbo.NOTA_INGRESO.IMPORTE, dbo.NOTA_INGRESO.PREC_TOTA, dbo.NOTA_INGRESO.OBSERVACIONES, 
                      dbo.NOTA_INGRESO.NRO_SERI_DOCU_CONT, dbo.NOTA_INGRESO.NRO_DOCU_CONT, dbo.CLIENTE_PROVEEDOR.RAZO_SOCI, 
                      TIPO_DOCUMENTO_a.DESC_TIPO_DOCU, UNID_OPER_a.DESC_UNID_OPER, UNID_OPER_b.DESC_UNID_OPER AS DESC_UNID_OPER_a, 
                      dbo.MONEDAS.DESC_MONE
FROM         dbo.NOTA_INGRESO INNER JOIN
                      dbo.CLIENTE_PROVEEDOR ON dbo.NOTA_INGRESO.CODI_CLIE_PROV = dbo.CLIENTE_PROVEEDOR.CODI_CLIE_PROV INNER JOIN
                      dbo.TIPO_DOCUMENTO TIPO_DOCUMENTO_a ON dbo.NOTA_INGRESO.CODI_TIPO_DOCU = TIPO_DOCUMENTO_a.CODI_TIPO_DOCU INNER JOIN
                      dbo.UNID_OPER UNID_OPER_b INNER JOIN
                      dbo.UNID_OPER UNID_OPER_a ON UNID_OPER_b.CODI_UNID_OPER = UNID_OPER_a.CODI_UNID_OPER ON 
                      dbo.NOTA_INGRESO.CODI_UNID_OPER_SOLI = UNID_OPER_a.CODI_UNID_OPER AND 
                      dbo.NOTA_INGRESO.CODI_UNID_OPER_DEST = UNID_OPER_b.CODI_UNID_OPER INNER JOIN
                      dbo.MONEDAS ON dbo.NOTA_INGRESO.CODI_MONE = dbo.MONEDAS.CODI_MONE
GO
