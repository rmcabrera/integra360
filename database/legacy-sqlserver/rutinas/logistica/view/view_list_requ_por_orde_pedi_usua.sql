CREATE VIEW [dbo].[view_list_requ_por_orde_pedi_usua]
AS
SELECT     dbo.LISTA_DE_REQUERIMIENTOS.CODI_LIST_REQU, dbo.LISTA_DE_REQUERIMIENTOS.CODI_PERS_RESP, 
                      dbo.LISTA_DE_REQUERIMIENTOS.CODI_UNID_OPER_SOLI, dbo.LISTA_DE_REQUERIMIENTOS.CODI_UNID_OPER_DEST, 
                      dbo.ORDEN_DE_PEDIDO.CODI_ORDE_PEDI, dbo.ORDEN_DE_PEDIDO.FECH_PEDI, dbo.ORDEN_DE_PEDIDO.ESTADO, dbo.USUARIOS.CODI_USUA, 
                      dbo.USUARIOS.APEL_1, dbo.USUARIOS.APEL_2, dbo.USUARIOS.NOMB_1, dbo.USUARIOS.NOMB_2, dbo.USUARIOS.LOGIN, 
                      dbo.ORDEN_DE_PEDIDO.CODI_LIST_REQU AS Expr1
FROM         dbo.LISTA_DE_REQUERIMIENTOS INNER JOIN
                      dbo.USUARIOS ON dbo.LISTA_DE_REQUERIMIENTOS.CODI_PERS_RESP = dbo.USUARIOS.CODI_USUA INNER JOIN
                      dbo.ORDEN_DE_PEDIDO ON dbo.LISTA_DE_REQUERIMIENTOS.CODI_LIST_REQU = dbo.ORDEN_DE_PEDIDO.CODI_LIST_REQU
GO
