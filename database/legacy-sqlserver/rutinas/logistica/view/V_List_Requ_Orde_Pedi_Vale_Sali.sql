CREATE VIEW [dbo].[V_List_Requ_Orde_Pedi_Vale_Sali]
AS
SELECT     dbo.LISTA_DE_REQUERIMIENTOS.CODI_LIST_REQU, dbo.ORDEN_DE_PEDIDO.CODI_ORDE_PEDI, dbo.DOCU_SALI_MATE.CODI_DOCU_SALI, 
                      dbo.LISTA_DE_REQUERIMIENTOS.FECH_LIST_REQU, dbo.DOCU_SALI_MATE.FECH_EMIS, dbo.ORDEN_DE_PEDIDO.FECH_PEDI, 
                      dbo.UNID_OPER.DESC_UNID_OPER
FROM         dbo.LISTA_DE_REQUERIMIENTOS INNER JOIN
                      dbo.ORDEN_DE_PEDIDO ON dbo.LISTA_DE_REQUERIMIENTOS.CODI_LIST_REQU = dbo.ORDEN_DE_PEDIDO.CODI_LIST_REQU INNER JOIN
                      dbo.DOCU_SALI_MATE ON dbo.ORDEN_DE_PEDIDO.CODI_ORDE_PEDI = dbo.DOCU_SALI_MATE.CODI_ORDE_PEDI INNER JOIN
                      dbo.UNID_OPER ON dbo.LISTA_DE_REQUERIMIENTOS.CODI_UNID_OPER_SOLI = dbo.UNID_OPER.CODI_UNID_OPER AND 
                      dbo.LISTA_DE_REQUERIMIENTOS.CODI_UNID_OPER_DEST = dbo.UNID_OPER.CODI_UNID_OPER AND 
                      dbo.DOCU_SALI_MATE.CODI_UNID_OPER_RECE = dbo.UNID_OPER.CODI_UNID_OPER
GO
