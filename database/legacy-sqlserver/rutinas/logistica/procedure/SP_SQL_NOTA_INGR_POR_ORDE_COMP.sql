CREATE PROCEDURE [dbo].[SP_SQL_NOTA_INGR_POR_ORDE_COMP]
	@Codi_Nota_Ingr [char](10),
	@Cantidad [int] OUTPUT,
	@Precio [decimal](18, 0) OUTPUT,
	@Codi_Prod [char](8) OUTPUT,
	@Codi_Mone [char](2) OUTPUT,
	@Nro_Cuen [char](7) OUTPUT
WITH EXECUTE AS CALLER
AS
SELECT DETALLE_ORDEN_COMPRA.CODI_PROD,   
         isnull(DETALLE_ORDEN_COMPRA.CANTIDAD,1),   
         isnull(DETALLE_ORDEN_COMPRA.PRECIO,0),   
         isnull(DETALLE_ORDEN_COMPRA.CODI_MONE,'01'),
         isnull(DETALLE_ORDEN_COMPRA.NRO_CUEN,'0')
    FROM NOTA_INGR_POR_ORDE_COMP,   
         DETALLE_ORDEN_COMPRA  
   WHERE ( NOTA_INGR_POR_ORDE_COMP.CODI_ORDE_COMP = DETALLE_ORDEN_COMPRA.CODI_ORDE_COMP ) and  
         ( ( NOTA_INGR_POR_ORDE_COMP.CODI_NOTA_INGR = @Codi_Nota_Ingr ) )
GO
