CREATE PROCEDURE [dbo].[SP_PRODUCTOS_COMPARA]
WITH EXECUTE AS CALLER
AS
BEGIN

set nocount on 
 

SELECT A.CODI_PROD, A.DESC_PROD, A.DESC_PRES, A.DESC_SUB_FAMI_PROD, 
       B.CODI_PROD, B.DESC_PROD, B.DESC_PRES, B.DESC_SUB_FAMI_PROD,
	A.codi_mone, B.codi_mone
FROM 
(SELECT  P.CODI_PROD,   
         P.DESC_PROD,   
	 PRE.DESC_PRES, 
         SF.DESC_SUB_FAMI_PROD, codi_mone
	
FROM 	 SIEP_AGROM.DBO.PRODUCTOS P (nolock) INNER JOIN SIEP_AGROM.DBO.SUB_FAMILIA_PRODUCTO SF (nolock) ON P.CODI_SUB_FAMI_PROD = SF.CODI_SUB_FAMI_PROD
         INNER JOIN SIEP_AGROM.DBO.PRESENTACION PRE (nolock) ON P.COD_PRES = PRE.COD_PRES ) A
left join 

(SELECT   P.CODI_PROD,   
         P.DESC_PROD,   
	 PRE.DESC_PRES, 
         SF.DESC_SUB_FAMI_PROD, codi_mone
FROM 	 SIEP_AGROG.DBO.PRODUCTOS P (nolock) INNER JOIN SIEP_AGROG.DBO.SUB_FAMILIA_PRODUCTO SF (nolock) ON P.CODI_SUB_FAMI_PROD = SF.CODI_SUB_FAMI_PROD
         INNER JOIN SIEP_AGROG.DBO.PRESENTACION PRE (nolock) ON P.COD_PRES = PRE.COD_PRES ) B
on A.codi_prod = B.codi_prod
	     
END
GO
