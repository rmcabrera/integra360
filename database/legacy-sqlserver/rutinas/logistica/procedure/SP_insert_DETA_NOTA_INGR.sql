CREATE PROCEDURE [dbo].[SP_insert_DETA_NOTA_INGR]
	@CODI_NOTA_INGR [char](10),
	@NRO_ITEM_NOTA_INGR [char](12),
	@CODI_PROD [char](8),
	@CANTIDAD [decimal](15, 4),
	@CODI_MONE [char](2),
	@PREC_UNIT [decimal](15, 4),
	@CODI_UNID_OPER [char](5),
	@NRO_CUEN [char](7)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_NOTA_INGRESO] 
	 ( [CODI_NOTA_INGR],
	 [NRO_ITEM_NOTA_INGR],
	 [CODI_PROD],
	 [CANTIDAD],
	 [CODI_MONE],
	 [PREC_UNIT],
	 [CODI_UNID_OPER],
	 [NRO_CUEN]) 
 
VALUES 
	( @CODI_NOTA_INGR,
	 @NRO_ITEM_NOTA_INGR,
	 @CODI_PROD,
	 @CANTIDAD,
	 @CODI_MONE,
	 @PREC_UNIT,
	 @CODI_UNID_OPER,
	 @NRO_CUEN)
GO
