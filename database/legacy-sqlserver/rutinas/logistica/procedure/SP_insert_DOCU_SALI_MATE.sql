CREATE PROCEDURE [dbo].[SP_insert_DOCU_SALI_MATE]
	@CODI_DOCU_SALI [char](10),
	@CODI_UNID_OPER_RECE [char](5),
	@CODI_TIPO_DOCU_SALI [char](4),
	@CODI_ORDE_PEDI [char](10),
	@CODI_PERS_EMIS [char](5),
	@CODI_PERS_RECE [char](5),
	@FECH_EMIS [datetime]
WITH EXECUTE AS CALLER
AS
INSERT INTO [DOCU_SALI_MATE] 
	 ( [CODI_DOCU_SALI],
	 [CODI_UNID_OPER_RECE],
	 [CODI_TIPO_DOCU_SALI],
	 [CODI_ORDE_PEDI],
	 [CODI_PERS_EMIS],
	 [CODI_PERS_RECE],
	 [FECH_EMIS]) 
 
VALUES 
	( @CODI_DOCU_SALI,
	 @CODI_UNID_OPER_RECE,
	 @CODI_TIPO_DOCU_SALI,
	 @CODI_ORDE_PEDI,
	 @CODI_PERS_EMIS,
	 @CODI_PERS_RECE,
	 @FECH_EMIS)
GO
