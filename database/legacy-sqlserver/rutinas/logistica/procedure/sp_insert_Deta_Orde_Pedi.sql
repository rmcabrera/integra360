CREATE PROCEDURE [dbo].[sp_insert_Deta_Orde_Pedi]
	@CODI_DETA_ORDE_PEDI [char](12),
	@CODI_ORDE_PEDI [char](10),
	@CODI_PROD [char](8),
	@CANTIDAD [decimal](9, 4),
	@NRO_CUEN [char](7),
	@ESTADO [char](1)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_ORDEN_DE_PEDIDO] 
	 ( [CODI_DETA_ORDE_PEDI],
	 [CODI_ORDE_PEDI],
	 [CODI_PROD],
	 [CANTIDAD],
	 [NRO_CUEN],
	 [ESTADO]) 
 
VALUES 
	(@CODI_DETA_ORDE_PEDI,
	 @CODI_ORDE_PEDI,
	 @CODI_PROD,
	 @CANTIDAD,
	 @NRO_CUEN,
	 @ESTADO)
GO
