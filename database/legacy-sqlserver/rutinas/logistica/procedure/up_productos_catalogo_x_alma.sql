CREATE PROCEDURE [dbo].[up_productos_catalogo_x_alma]
	@codialma [char](2)
WITH EXECUTE AS CALLER
AS
--- EL PRECIO PROMEDIO DEBE SER POR ALMACEN

SELECT    dbo.FAMILIA_PRODUCTO.CODI_FAMI_PROD, dbo.FAMILIA_PRODUCTO.DESC_FAMI_PROD, dbo.FAMILIA_PRODUCTO.PROD_SERV, 
                      dbo.SUB_FAMILIA_PRODUCTO.CODI_SUB_FAMI_PROD, dbo.SUB_FAMILIA_PRODUCTO.DESC_SUB_FAMI_PROD, dbo.PRODUCTOS.CODI_PROD, 
                      dbo.PRODUCTOS.DESC_PROD, dbo.PRODUCTOS.CODI_UNID_MEDI, dbo.PRODUCTOS.CODI_MONE, dbo.PRODUCTOS.PREC_PROM, 
                      dbo.ALMACEN_PRODUCTO.STOCK_ALMA  ,  dbo.ALMACEN_PRODUCTO.STOCK_TEMP_ALMA , dbo.PRODUCTOS.UBICACION, dbo.PRODUCTOS.NRO_CUEN, 
                     dbo.CUENTAS_CONTABLE.DESC_CUEN , 

		
		ALMACEN_PRODUCTO.CODI_ALMA
FROM      dbo.FAMILIA_PRODUCTO     

		LEFT OUTER JOIN  dbo.SUB_FAMILIA_PRODUCTO 	ON dbo.FAMILIA_PRODUCTO.CODI_FAMI_PROD = dbo.SUB_FAMILIA_PRODUCTO.CODI_FAMI_PROD
		LEFT OUTER JOIN dbo.PRODUCTOS 			ON dbo.SUB_FAMILIA_PRODUCTO.CODI_SUB_FAMI_PROD = dbo.PRODUCTOS.CODI_SUB_FAMI_PROD
		left  JOIN  dbo.CUENTAS_CONTABLE 	      		ON dbo.PRODUCTOS.NRO_CUEN = dbo.CUENTAS_CONTABLE.NRO_CUEN 

		left JOIN ALMACEN_PRODUCTO 			ON  PRODUCTOS.CODI_PROD= ALMACEN_PRODUCTO.CODI_PROD AND  ALMACEN_PRODUCTO.CODI_ALMA=@CODIALMA


ORDER BY dbo.FAMILIA_PRODUCTO.CODI_FAMI_PROD, dbo.SUB_FAMILIA_PRODUCTO.CODI_SUB_FAMI_PROD, dbo.PRODUCTOS.CODI_PROD
GO
