CREATE PROCEDURE [dbo].[SP_UPDATE_DETA_SALI_MATE]
	@CODI_DOCU_SALI_1 [char](1),
	@CODI_PROD_2 [char](1),
	@CODI_DOCU_SALI_3 [char](10),
	@NRO_CUEN_4 [char](7),
	@CODI_PROD_5 [char](8),
	@CANTIDAD_6 [decimal](9, 2)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_SALIDA_MATERIALES] 

SET  [CODI_DOCU_SALI]	 = @CODI_DOCU_SALI_3,
	 [NRO_CUEN]	 = @NRO_CUEN_4,
	 [CODI_PROD]	 = @CODI_PROD_5,
	 [CANTIDAD]	 = @CANTIDAD_6 

WHERE 
	( [CODI_DOCU_SALI]	 = @CODI_DOCU_SALI_1 AND
	 [CODI_PROD]	 = @CODI_PROD_2)
GO
