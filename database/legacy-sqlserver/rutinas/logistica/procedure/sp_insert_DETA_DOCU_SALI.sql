CREATE PROCEDURE [dbo].[sp_insert_DETA_DOCU_SALI]
	@CODI_DETA_DOCU_SALI [char](12),
	@CODI_DOCU_SALI [char](10),
	@NRO_CUEN [char](7),
	@CODI_PROD [char](8),
	@CANTIDAD [numeric](15, 4),
	@PREC_PROM [decimal](15, 4)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_DOCU_SALI] 
	 ([CODI_DETA_DOCU_SALI], 
	 [CODI_DOCU_SALI],
	 [NRO_CUEN],
	 [CODI_PROD],
	 [CANTIDAD],
	 [PREC_PROM]) 
 
VALUES 
	(@CODI_DETA_DOCU_SALI,
	  @CODI_DOCU_SALI,
	 @NRO_CUEN,
	 @CODI_PROD,
	 @CANTIDAD,
	 @PREC_PROM)
GO
