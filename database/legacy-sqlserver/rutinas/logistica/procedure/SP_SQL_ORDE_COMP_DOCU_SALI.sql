CREATE PROCEDURE [dbo].[SP_SQL_ORDE_COMP_DOCU_SALI]
	@Codi_Docu_Sali [char](10),
	@Cantidad [int] OUTPUT,
	@Precio [decimal](18, 0) OUTPUT,
	@Codi_Prod [char](8) OUTPUT,
	@Codi_Mone [char](2) OUTPUT
WITH EXECUTE AS CALLER
AS
SELECT DETALLE_ORDEN_COMPRA.CODI_PROD, DETALLE_ORDEN_COMPRA.CANTIDAD,   
         DETALLE_ORDEN_COMPRA.PRECIO, DETALLE_ORDEN_COMPRA.CODI_MONE  
    FROM DETALLE_ORDEN_COMPRA,   
         ORDEN_DE_COMPRA,   
         ORDE_COMP_DOCU_SALI  
   WHERE ( ORDEN_DE_COMPRA.CODI_ORDE_COMP = DETALLE_ORDEN_COMPRA.CODI_ORDE_COMP ) and  
         ( ORDE_COMP_DOCU_SALI.CODI_ORDE_COMP = ORDEN_DE_COMPRA.CODI_ORDE_COMP ) and  
         ( ( ORDE_COMP_DOCU_SALI.CODI_DOCU_SALI = @Codi_Docu_Sali ) )
GO
