CREATE PROCEDURE [dbo].[sp_delete_ORDE_COMP_PEDI_COTI]
	@CODI_ORDE_COMP [char](10),
	@CODI_DOCU [char](10),
	@CODI_TIPO_DOCU [char](4)
WITH EXECUTE AS CALLER
AS
DELETE [ORDEN_COMPRA_PEDIDO_COTIZA] 

WHERE 
	( [CODI_ORDE_COMP]	 = @CODI_ORDE_COMP AND
	 [CODI_DOCU]	 = @CODI_DOCU AND
	 [CODI_TIPO_DOCU]	 = @CODI_TIPO_DOCU)
GO
