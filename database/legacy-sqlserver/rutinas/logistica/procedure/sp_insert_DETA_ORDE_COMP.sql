CREATE PROCEDURE [dbo].[sp_insert_DETA_ORDE_COMP]
	@CODI_DETA_ORDE_COMP [char](12),
	@CODI_ORDE_COMP [char](10),
	@CODI_PROD [char](8),
	@CANTIDAD [decimal](18, 4),
	@PRECIO [decimal](18, 4),
	@CODI_MONE [char](2),
	@NRO_CUEN [char](7)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_ORDEN_COMPRA] 
	 ( [CODI_DETA_ORDE_COMP],
	 [CODI_ORDE_COMP],
	 [CODI_PROD],
	 [CANTIDAD],
	 [PRECIO],
	 [CODI_MONE],
	 [NRO_CUEN]) 
 
VALUES 
	( @CODI_DETA_ORDE_COMP,
	 @CODI_ORDE_COMP,
	 @CODI_PROD,
	 @CANTIDAD,
	 @PRECIO,
	 @CODI_MONE,
	 @NRO_CUEN)
GO
