CREATE PROCEDURE [dbo].[sp_update_DETA_ORDE_COMP]
	@CODI_DETA_ORDE_COMP_PRIN [char](12),
	@CODI_DETA_ORDE_COMP_SET [char](12),
	@CODI_ORDE_COMP [char](10),
	@CODI_PROD [char](8),
	@CANTIDAD [decimal](9, 2),
	@PRECIO [decimal](9, 2),
	@CODI_MONE [char](2),
	@NRO_CUEN [char](7)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_ORDEN_COMPRA] 

SET  [CODI_DETA_ORDE_COMP]	 = @CODI_DETA_ORDE_COMP_SET,
	 [CODI_ORDE_COMP]	 = @CODI_ORDE_COMP,
	 [CODI_PROD]	 = @CODI_PROD,
	 [CANTIDAD]	 = @CANTIDAD,
	 [PRECIO]	 = @PRECIO,
	 [CODI_MONE]	 = @CODI_MONE,
	 [NRO_CUEN]	 = @NRO_CUEN 

WHERE 
	( [CODI_DETA_ORDE_COMP]	 = @CODI_DETA_ORDE_COMP_PRIN)
GO
