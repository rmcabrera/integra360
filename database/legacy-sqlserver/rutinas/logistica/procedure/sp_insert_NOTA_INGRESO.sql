	@CODI_UNID_OPER_SOLI [char](5),
	@CODI_UNID_OPER_DEST [char](5),
	@FECH_NOTA_INGR_6 [datetime],
	@TIPO_NOTA_INGR_7 [char](20),
	@IMPORTE_8 [decimal](9, 4),
	@CODI_PERS_VIST_BUEN_9 [char](5),
	@CODI_PERS_ELAB_10 [char](5),
	@CODI_MONE_11 [char](2),
	@PREC_TOTA_12 [decimal](9, 4),
	@OBSERVACIONES_13 [varchar](100)
WITH EXECUTE AS CALLER
AS
INSERT INTO [NOTA_INGRESO] 
	 ( [CODI_NOTA_INGR],
	 [CODI_CLIE_PROV],
	 [CODI_TIPO_DOCU],
	 [NRO_SERI],
	 [NRO_DOCU],
	 [CODI_UNID_OPER_SOLI],
	 [CODI_UNID_OPER_DEST],
	 [FECH_NOTA_INGR],
	 [TIPO_NOTA_INGR],
	 [IMPORTE],
	 [CODI_PERS_VIST_BUEN],
	 [CODI_PERS_ELAB],
	 [CODI_MONE],
	 [PREC_TOTA],
	 [OBSERVACIONES]) 
 
VALUES 
	( @CODI_NOTA_INGR_1,
	 @CODI_CLIE_PROV_2,
	 @CODI_TIPO_DOCU_3,
	 @NRO_SERI_4,
	 @NRO_DOCU_5,
	 @CODI_UNID_OPER_SOLI,
	 @CODI_UNID_OPER_DEST,
	 @FECH_NOTA_INGR_6,
	 @TIPO_NOTA_INGR_7,
	 @IMPORTE_8,
	 @CODI_PERS_VIST_BUEN_9,
	 @CODI_PERS_ELAB_10,
	 @CODI_MONE_11,
	 @PREC_TOTA_12,
	 @OBSERVACIONES_13)
GO
