CREATE PROCEDURE [dbo].[SP_INSERT_DETA_SALI_MATE]
	@CODI_DOCU_SALI_1 [char](10),
	@NRO_CUEN_2 [char](7),
	@CODI_PROD_3 [char](8),
	@CANTIDAD_4 [decimal](10, 4)
WITH EXECUTE AS CALLER
AS
INSERT INTO [DETALLE_SALIDA_MATERIALES] 
	 ( [CODI_DOCU_SALI],
	 [NRO_CUEN],
	 [CODI_PROD],
	 [CANTIDAD]) 
 
VALUES 
	( @CODI_DOCU_SALI_1,
	 @NRO_CUEN_2,
	 @CODI_PROD_3,
	 @CANTIDAD_4)
GO
