CREATE PROCEDURE [dbo].[SP_update_DETA_LIST_REQU]
	@CODI_DETA_LIST_REQU [char](10),
	@CODI_LIST_REQU [char](8),
	@CODI_PROD [char](8),
	@CANTIDAD [decimal](9, 2),
	@NRO_CUEN [char](7)
WITH EXECUTE AS CALLER
AS
UPDATE [DETALLE_LISTAREQUERIMIENTOS] 

SET  	 [CODI_LIST_REQU]	 = @CODI_LIST_REQU,
	 [CODI_PROD]	 = @CODI_PROD,
	 [CANTIDAD]	 = @CANTIDAD,
	 [NRO_CUEN]	 = @NRO_CUEN 

WHERE 
	( [CODI_DETA_LIST_REQU]	 = @CODI_DETA_LIST_REQU)
GO
