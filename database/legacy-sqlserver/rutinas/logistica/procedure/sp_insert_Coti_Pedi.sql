CREATE PROCEDURE [dbo].[sp_insert_Coti_Pedi]
	@CODI_COTI [char](10),
	@FECH_COTI [datetime],
	@TIEM_PLAZ_CRED [int],
	@CODI_UNID_MEDI [char](2),
	@ESTADO [char](1),
	@CODI_MONE [char](2),
	@PREC_TOTA_COTI [decimal](9, 2),
	@CODI_ORDE_PEDI [char](10),
	@CODI_LIST_REQU_ORIG [char](8)
WITH EXECUTE AS CALLER
AS
INSERT INTO [COTIZACION_DE_PEDIDOS] 
	 ( [CODI_COTI],
	 [FECH_COTI],
	 [TIEM_PLAZ_CRED],
	 [CODI_UNID_MEDI],
	 [ESTADO],
	 [CODI_MONE],
	 [PREC_TOTA_COTI],
	 [CODI_ORDE_PEDI],
	 [CODI_LIST_REQU_ORIG]) 
 
VALUES 
	( @CODI_COTI,
	 @FECH_COTI,
	 @TIEM_PLAZ_CRED,
	 @CODI_UNID_MEDI,
	 @ESTADO,
	 @CODI_MONE,
	 @PREC_TOTA_COTI,
	 @CODI_ORDE_PEDI,
	 @CODI_LIST_REQU_ORIG)
GO
