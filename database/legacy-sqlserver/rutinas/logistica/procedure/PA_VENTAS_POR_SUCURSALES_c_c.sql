CREATE PROCEDURE [dbo].[PA_VENTAS_POR_SUCURSALES_c_c]
	@TIPO [char](1),
	@CODI_TIPO_PAGO [numeric](18, 0),
	@f1 [datetime],
	@f2 [datetime]
WITH EXECUTE AS CALLER
AS
--declare @TIPO CHAR(1) ,  @ANIO int ,  @CODI_TIPO_PAGO NUMERIC , @f1 datetime , @f2 datetime  --
--select @TIPO = 0 ,  @ANIO =2012,  @CODI_TIPO_PAGO =0, @f1 ='01/10/2010', @f2 ='11/10/2010'  
  
set nocount on  

SELECT NEMO_ALMA,'',SUM(VALO_CONTADO_ENERO) VALO_CONTADO_ENERO,
SUM(VALO_CONTADO_FEBRERO) VALO_CONTADO_FEBRERO,
SUM(VALO_CONTADO_MAR) VALO_CONTADO_MAR,
SUM(VALO_CONTADO_ABRIL) VALO_CONTADO_ABRIL,
SUM(VALO_CONTADO_MAYO) VALO_CONTADO_MAYO,
SUM(VALO_CONTADO_JUNIO) VALO_CONTADO_JUNIO,
SUM(VALO_CONTADO_JULIO) VALO_CONTADO_JULIO,
SUM(VALO_CONTADO_AGOS) VALO_CONTADO_AGOS,
SUM(VALO_CONTADO_SET) VALO_CONTADO_SET,
SUM(VALO_CONTADO_OCT) VALO_CONTADO_OCT,
SUM(VALO_CONTADO_NOV) VALO_CONTADO_NOV,
SUM(VALO_CONTADO_DIC) VALO_CONTADO_DIC,

SUM(VALO_CREDITO_ENERO) VALO_CREDITO_ENERO,
SUM(VALO_CREDITO_FEBRERO) VALO_CREDITO_FEBRERO,
SUM(VALO_CREDITO_MAR) VALO_CREDITO_MAR,
SUM(VALO_CREDITO_ABRIL) VALO_CREDITO_ABRIL,
SUM(VALO_CREDITO_MAYO) VALO_CREDITO_MAYO,
SUM(VALO_CREDITO_JUNIO) VALO_CREDITO_JUNIO,
SUM(VALO_CREDITO_JULIO) VALO_CREDITO_JULIO,
SUM(VALO_CREDITO_AGOS) VALO_CREDITO_AGOS,
SUM(VALO_CREDITO_SET) VALO_CREDITO_SET,
SUM(VALO_CREDITO_OCT) VALO_CREDITO_OCT,
SUM(VALO_CREDITO_NOV) VALO_CREDITO_NOV,
SUM(VALO_CREDITO_DIC) VALO_CREDITO_DIC

 FROM 
(SELECT NEMO_ALMA,'' TIPO, CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_ENERO) ELSE 0 END VALO_CONTADO_ENERO,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_FEBRERO) ELSE 0 END VALO_CONTADO_FEBRERO,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_MAR) ELSE 0 END VALO_CONTADO_MAR,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_ABRIL) ELSE 0 END VALO_CONTADO_ABRIL,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_MAYO) ELSE 0 END VALO_CONTADO_MAYO,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_JUNIO) ELSE 0 END VALO_CONTADO_JUNIO,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_JULIO) ELSE 0 END VALO_CONTADO_JULIO,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_AGOS) ELSE 0 END VALO_CONTADO_AGOS,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_SET) ELSE 0 END VALO_CONTADO_SET,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_OCT) ELSE 0 END VALO_CONTADO_OCT,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_NOV) ELSE 0 END VALO_CONTADO_NOV,
CASE WHEN TIPO_VENTA='CONTADO' THEN SUM(VALO_VENTA_DIC) ELSE 0 END VALO_CONTADO_DIC,

CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_ENERO) ELSE 0 END VALO_CREDITO_ENERO,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_FEBRERO) ELSE 0 END VALO_CREDITO_FEBRERO,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_MAR) ELSE 0 END VALO_CREDITO_MAR,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_ABRIL) ELSE 0 END VALO_CREDITO_ABRIL,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_MAYO) ELSE 0 END VALO_CREDITO_MAYO,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_JUNIO) ELSE 0 END VALO_CREDITO_JUNIO,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_JULIO) ELSE 0 END VALO_CREDITO_JULIO,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_AGOS) ELSE 0 END VALO_CREDITO_AGOS,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_SET) ELSE 0 END VALO_CREDITO_SET,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_OCT) ELSE 0 END VALO_CREDITO_OCT,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_NOV) ELSE 0 END VALO_CREDITO_NOV,
CASE WHEN TIPO_VENTA='CREDITO' THEN SUM(VALO_VENTA_DIC) ELSE 0 END VALO_CREDITO_DIC


FROM
(select  SUC.NEMO_ALMA ,   
     ( CASE  FAC.CODI_TIPO_PAGO WHEN 1 THEN 'CONTADO' WHEN 4 THEN 'CREDITO' ELSE '' END) AS 'TIPO_VENTA' ,  
     
     ---Valor Venta--------------------   
     SUM(case month(FAC.FECH_FACT) when '1' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_ENERO ,  
     SUM(case month(FAC.FECH_FACT) when '2' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_FEBRERO,  
     SUM(case month(FAC.FECH_FACT) when '3' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_MAR,  
     SUM(case month(FAC.FECH_FACT) when '4' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_ABRIL,  
     SUM(case month(FAC.FECH_FACT) when '5' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_MAYO,  
     SUM(case month(FAC.FECH_FACT) when '6' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_JUNIO,  
     SUM(case month(FAC.FECH_FACT) when '7' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_JULIO,  
     SUM(case month(FAC.FECH_FACT) when '8' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_AGOS,  
     SUM(case month(FAC.FECH_FACT) when '9' then  (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM *  FD.PREC_ITEM ) else 0 end) as VALO_VENTA_SET,  
     SUM(case month(FAC.FECH_FACT) when '10' then (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM * FD.PREC_ITEM ) else 0 end) as VALO_VENTA_OCT,  
     SUM(case month(FAC.FECH_FACT) when '11' then (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM * FD.PREC_ITEM ) else 0 end) as VALO_VENTA_NOV,  
     SUM(case month(FAC.FECH_FACT) when '12' then (CASE FAC.CODI_MONE WHEN '01' THEN 1 ELSE FAC.tcambio END ) * ( FD.CANT_ITEM * FD.PREC_ITEM ) else 0 end) as VALO_VENTA_DIC  
     ---fin de valor venta ----------  
    
    FROM dbo.ALMACEN as SUC (nolock)    
  inner join dbo.FACTURA as FAC (nolock)  on suc.codi_alma=FAC.codi_alma  
  inner join dbo.FACTURA_DETALLE as FD (nolock)  on FAC.codi_fact = FD.codi_fact  
  inner join dbo.PRODUCTOS as P (nolock) on FD.codi_prod=P.Codi_prod  
    where --year(FAC.FECH_FACT)=@ANIO     
   cast(convert(char(10), fac.fech_fact,103) as datetime) between @f1 and @f2 and    
  ( isnull(FAC.ESTADO,'')<>'A')  
  group by  SUC.NEMO_ALMA, FAC.CODI_TIPO_PAGO  
)  sql
GROUP BY NEMO_ALMA,TIPO_VENTA) SQLD
  
GROUP BY NEMO_ALMA
GO
