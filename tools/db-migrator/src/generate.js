'use strict';
/**
 * Generador: script SQL Server legado -> PostgreSQL (Flyway por microservicio)
 *            + entidades JPA (Hibernate Reactive Panache) + catalogo de metadatos
 *            + inventario de procedimientos almacenados con estrategia de migracion.
 *
 * Uso: node src/generate.js <script.sql> <raiz-proyecto>
 */
const fs = require('fs');
const path = require('path');
const { parse } = require('./parse-mssql');
const { SERVICES, classify } = require('./domains');
const { pgName, q, javaClass, javaField, label, truncate63 } = require('./naming');
const { mapType, mapDefault, mapComputed } = require('./types');

const [, , scriptFile, root] = process.argv;
if (!scriptFile || !root) { console.error('uso: node src/generate.js <script.sql> <raiz-proyecto>'); process.exit(1); }
const MAIN_DB = process.env.MAIN_DB || 'SI_AGROG';
const BASE_PKG = 'pe.sige';

const write = (f, s) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s.replace(/\r?\n/g, '\n'), 'utf8'); };
const sqlStr = s => `'${String(s).replace(/'/g, "''")}'`;
const HEADER = '-- Generado por tools/db-migrator a partir del script SQL Server legado. No editar a mano:\n-- los cambios evolutivos van en migraciones nuevas (V100__..., V101__...).\n';

console.log('Parseando', scriptFile);
const { tables, routines } = parse(scriptFile, MAIN_DB);
console.log('tablas', tables.length, 'rutinas', routines.length);

// ---------------------------------------------------------------- modelo normalizado
const warnings = [];
const model = new Map(); // legacyLower -> table model
for (const t of tables) {
  const svc = classify(t.name);
  const pgT = pgName(t.name);
  const usedCols = new Set();
  const cols = t.columns.map(c => {
    let n = pgName(c.name);
    while (usedCols.has(n)) n = n + '_x';
    usedCols.add(n);
    let mapped, generated = null;
    if (c.computed) {
      const cm = mapComputed(c.computed);
      if (cm) { mapped = { pg: cm.pg, java: cm.java }; generated = cm.expr; }
      else { mapped = { pg: 'text', java: 'String' }; warnings.push(`${t.name}.${c.name}: columna calculada no traducida (${c.computed}); se crea como columna normal`); }
    } else mapped = mapType(c);
    if (mapped.warn) warnings.push(`${t.name}.${c.name}: ${mapped.warn}`);
    const def = c.default != null ? mapDefault(c.default, mapped) : null;
    if (c.default != null && def == null) warnings.push(`${t.name}.${c.name}: DEFAULT ${c.default} no traducido`);
    return { legacy: c.name, pg: n, type: mapped, nullable: c.nullable, identity: c.identity, default: def, generated, computedLegacy: c.computed, comment: c.comment, field: javaField(n) };
  });
  // unicidad de nombres de campo Java
  const usedF = new Set();
  cols.forEach(c => { while (usedF.has(c.field)) c.field += 'X'; usedF.add(c.field); });

  const byLegacy = n => cols.find(c => c.legacy.toLowerCase() === n.toLowerCase());
  let pk = t.pk ? t.pk.columns.map(byLegacy).filter(Boolean) : [];
  let surrogate = false;
  if (!pk.length) {
    const ident = cols.find(c => c.identity);
    if (ident) pk = [ident];
    else {
      surrogate = true;
      const idCol = { legacy: null, pg: cols.some(c => c.pg === 'id') ? 'sige_id' : 'id', type: { pg: 'bigint', java: 'Long' }, nullable: false, identity: true, surrogate: true, comment: 'Clave sustituta agregada en la migracion (la tabla legado no tenia PK)' };
      idCol.field = javaField(idCol.pg);
      cols.unshift(idCol);
      pk = [idCol];
    }
  }
  pk.forEach(c => { c.nullable = false; c.pk = true; });
  model.set(t.name.toLowerCase(), { legacy: t.name, pg: pgT, svc, cols, pk, surrogate, t, cls: javaClass(t.name) });
}

// clases unicas por servicio
for (const svc of Object.keys(SERVICES)) {
  const used = new Set();
  for (const m of model.values()) if (m.svc === svc) { while (used.has(m.cls)) m.cls += 'T'; used.add(m.cls); }
}

// ---------------------------------------------------------------- SQL por servicio
const crossFks = [];
const perSvc = {};
for (const svc of Object.keys(SERVICES)) perSvc[svc] = { ddl: [], fk: [], idx: [], cmt: [], names: new Set(), tables: [] };
const uniqueName = (svc, n) => { let x = truncate63(n), i = 2; while (perSvc[svc].names.has(x)) x = truncate63(n + '_' + i++); perSvc[svc].names.add(x); return x; };

for (const m of model.values()) {
  const S = perSvc[m.svc];
  S.tables.push(m);
  const lines = m.cols.map(c => {
    let l = `    ${q(c.pg)} ${c.type.pg}`;
    if (c.generated) return l + ` GENERATED ALWAYS AS ${c.generated} STORED`;
    if (c.identity) l += ' GENERATED BY DEFAULT AS IDENTITY';
    if (!c.nullable) l += ' NOT NULL';
    if (c.default != null && !c.identity) l += ` DEFAULT ${c.default}`;
    return l;
  });
  lines.push('    audit_created_at timestamptz NOT NULL DEFAULT now()', '    audit_updated_at timestamptz', '    audit_user varchar(60)', '    row_version bigint NOT NULL DEFAULT 0');
  lines.push(`    CONSTRAINT ${uniqueName(m.svc, 'pk_' + m.pg)} PRIMARY KEY (${m.pk.map(c => q(c.pg)).join(', ')})`);
  for (const u of m.t.uniques) {
    const cs = u.columns.map(n => m.cols.find(c => c.legacy && c.legacy.toLowerCase() === n.toLowerCase())).filter(Boolean);
    if (cs.length) lines.push(`    CONSTRAINT ${uniqueName(m.svc, 'uq_' + m.pg + '_' + pgName(u.name))} UNIQUE (${cs.map(c => q(c.pg)).join(', ')})`);
  }
  S.ddl.push(`-- ${m.legacy}${m.surrogate ? '  (sin PK en el legado: se agrega clave sustituta)' : ''}\nCREATE TABLE ${q(m.pg)} (\n${lines.join(',\n')}\n);\n`);

  // comentarios
  S.cmt.push(`COMMENT ON TABLE ${q(m.pg)} IS ${sqlStr((m.t.comment ? m.t.comment + ' | ' : '') + 'Legado: dbo.' + m.legacy)};`);
  for (const c of m.cols) {
    const parts = [];
    if (c.comment) parts.push(c.comment);
    if (c.legacy && c.legacy !== c.pg && c.legacy.toLowerCase() !== c.pg) parts.push('Legado: ' + c.legacy);
    if (c.computedLegacy && !c.generated) parts.push('Era columna calculada en SQL Server: ' + c.computedLegacy);
    if (parts.length) S.cmt.push(`COMMENT ON COLUMN ${q(m.pg)}.${q(c.pg)} IS ${sqlStr(parts.join(' | '))};`);
  }

  // FKs
  const idxLeading = new Set();
  for (const ix of m.t.indexes) {
    const cs = ix.columns.map(n => m.cols.find(c => c.legacy && c.legacy.toLowerCase() === n.toLowerCase())).filter(Boolean);
    if (!cs.length) continue;
    const inc = ix.include.map(n => m.cols.find(c => c.legacy && c.legacy.toLowerCase() === n.toLowerCase())).filter(Boolean)
      .filter(c => !cs.includes(c));
    const nm = uniqueName(m.svc, 'ix_' + m.pg + '_' + pgName(ix.name).replace(/^(ix|idx)_/, ''));
    S.idx.push(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${nm} ON ${q(m.pg)} (${cs.map(c => q(c.pg)).join(', ')})${inc.length ? ` INCLUDE (${inc.map(c => q(c.pg)).join(', ')})` : ''};`);
    idxLeading.add(cs.map(c => c.pg).join(','));
  }
  const pkLead = m.pk.map(c => c.pg).join(',');
  for (const fk of m.t.fks) {
    const ref = model.get(fk.refTable.toLowerCase());
    const cs = fk.columns.map(n => m.cols.find(c => c.legacy && c.legacy.toLowerCase() === n.toLowerCase()));
    if (!ref || cs.some(x => !x)) { warnings.push(`FK ${fk.name} omitida: referencia no resuelta`); continue; }
    const rcs = fk.refColumns.map(n => ref.cols.find(c => c.legacy && c.legacy.toLowerCase() === n.toLowerCase()));
    if (rcs.some(x => !x)) { warnings.push(`FK ${fk.name} omitida: columnas referenciadas no resueltas`); continue; }
    const key = rcs.map(c => c.pg).sort().join(',');
    const refKeys = [ref.pk.map(c => c.pg).sort().join(',')]
      .concat(ref.t.uniques.map(u => u.columns.map(pgName).sort().join(',')))
      .concat(ref.t.indexes.filter(i => i.unique && !i.include.length).map(i => i.columns.map(pgName).sort().join(',')));
    if (!refKeys.includes(key)) { warnings.push(`FK ${fk.name} omitida: ${ref.legacy}(${key}) no es PK/UNIQUE en el destino`); continue; }
    if (ref.svc !== m.svc) {
      crossFks.push({ from: `${m.svc}.${m.pg}(${cs.map(c => c.pg).join(',')})`, to: `${ref.svc}.${ref.pg}(${rcs.map(c => c.pg).join(',')})`, legacy: fk.name });
      continue;
    }
    // tipos compatibles?
    const mismatch = cs.some((c, i) => c.type.pg !== rcs[i].type.pg);
    const nm = uniqueName(m.svc, 'fk_' + m.pg + '_' + ref.pg);
    S.fk.push(`ALTER TABLE ${q(m.pg)} ADD CONSTRAINT ${nm} FOREIGN KEY (${cs.map(c => q(c.pg)).join(', ')}) REFERENCES ${q(ref.pg)} (${rcs.map(c => q(c.pg)).join(', ')})${fk.onDelete ? ' ON DELETE CASCADE' : ''}${fk.onUpdate ? ' ON UPDATE CASCADE' : ''} NOT VALID;${mismatch ? ' -- tipos distintos en el legado' : ''}`);
    const lead = cs.map(c => c.pg).join(',');
    if (!idxLeading.has(lead) && !pkLead.startsWith(lead)) {
      idxLeading.add(lead);
      S.idx.push(`CREATE INDEX ${uniqueName(m.svc, 'ix_' + m.pg + '_fk_' + cs.map(c => c.pg).join('_'))} ON ${q(m.pg)} (${cs.map(c => q(c.pg)).join(', ')}); -- indice de FK (mejora)`);
    }
  }
}

